"""Turns AD1C's cty.dat into core/js/spotmap/cty-data.js for the Spot Map.

    python -I core/tools/cty/make_cty_js.py path/to/cty.dat

Download cty.dat from https://www.country-files.com/ (free to use). Run this
again whenever a new cty.dat comes out; it rewrites cty-data.js. Each output
line is one country: name|lat|lon|tokens, longitude east positive (cty.dat
has west positive). A token is a prefix, or =CALL for an exact callsign,
with @lat/lon when cty.dat gives that prefix its own position.
"""
import os
import re
import sys

TOKEN = re.compile(r'^(=?)([A-Z0-9/]+)((?:\(\d+\)|\[\d+\]|<[-\d.]+/[-\d.]+>|\{\w+\}|~[-\d.]+~)*)$')
LATLON = re.compile(r'<([-\d.]+)/([-\d.]+)>')


def num(s):
    return ('%.2f' % float(s)).rstrip('0').rstrip('.')


def main(src):
    with open(src, encoding='latin-1') as f:
        text = f.read()
    lines = []
    for rec in text.split(';'):
        rec = rec.strip()
        if not rec:
            continue
        head, _, body = rec.partition('\n')
        parts = [p.strip() for p in head.split(':')]
        if len(parts) < 8:
            continue
        name, lat, lon = parts[0], parts[4], parts[5]
        toks = []
        for raw in body.replace('\n', ' ').split(','):
            raw = raw.strip()
            m = TOKEN.match(raw)
            if not m:
                continue
            tok = m.group(1) + m.group(2)
            ll = LATLON.search(m.group(3))
            if ll:
                tok += '@%s/%s' % (num(ll.group(1)), num(-float(ll.group(2))))
            toks.append(tok)
        name = name.replace('|', '/').replace('`', "'")
        lines.append('%s|%s|%s|%s' % (name, num(lat), num(-float(lon)), ','.join(toks)))
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, '..', '..', 'js', 'spotmap', 'cty-data.js')
    with open(out, 'w', encoding='ascii', newline='\r\n') as f:
        f.write('// Generated by core/tools/cty/make_cty_js.py from AD1C\'s cty.dat\n')
        f.write('// (https://www.country-files.com/, free to use). Do not edit by hand:\n')
        f.write('// download a new cty.dat and run the script again.\n')
        f.write('// One country per line: name|lat|lon (east positive)|prefixes, =exact calls.\n')
        f.write('export const CTY = `\n')
        for l in lines:
            f.write(l + '\n')
        f.write('`;\n')
    print('countries', len(lines), 'bytes', os.path.getsize(out))


if __name__ == '__main__':
    main(sys.argv[1])
